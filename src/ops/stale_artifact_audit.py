#!/usr/bin/env python3
"""Stale-artifact audit (Round 11, informational -- lists, never deletes).

Lists every file under docs/figures/, docs/paper_assets/ and
models/artifacts/ whose mtime predates the current pipeline run start
(recorded by main.py in results/logs/pipeline/.run_start_utc; falls back to
the newest results/logs/pipeline/*.log mtime when that marker is absent).
Anything listed was NOT regenerated by the last run and is a candidate
leftover. Writes results/stale_artifacts.json. Always exits 0 -- this stage
informs a human cleanup decision; it never deletes and never fails.

(Destructive pruning happens ONLY in src/analysis/generate_pdp.py, which
removes PDP PNGs whose (model, feature) pair is not in the current run's PDP
summaries.)

Run: python src/ops/stale_artifact_audit.py
"""
import json
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUN_START_MARKER = ROOT / 'results' / 'logs' / 'pipeline' / '.run_start_utc'
OUT = ROOT / 'results' / 'stale_artifacts.json'
WATCH_DIRS = ['docs/figures', 'docs/paper_assets', 'models/artifacts']


def main():
    run_start = None
    if RUN_START_MARKER.exists():
        try:
            run_start = float(RUN_START_MARKER.read_text().strip())
        except ValueError:
            run_start = None
    if run_start is None:
        log_dir = ROOT / 'results' / 'logs' / 'pipeline'
        logs = list(log_dir.glob('*.log'))
        if logs:
            run_start = max(f.stat().st_mtime for f in logs)

    report = {'run_start_epoch': run_start,
              'run_start_note': (
                  'marker written by main.py at run start' if run_start else
                  'no run-start marker or pipeline logs found; all files '
                  'listed as unaudited'),
              'watch_dirs': WATCH_DIRS,
              'stale_files': {}}
    for wd in WATCH_DIRS:
        base = ROOT / wd
        stale = []
        if base.exists():
            for f in sorted(base.rglob('*')):
                if not f.is_file():
                    continue
                if run_start is None or f.stat().st_mtime < run_start - 1:
                    stale.append({
                        'file': f.relative_to(ROOT).as_posix(),
                        'size_kb': round(f.stat().st_size / 1024.0, 1),
                        'age_days': round(
                            (time.time() - f.stat().st_mtime) / 86400.0, 1)})
        report['stale_files'][wd] = stale
        print(f'{wd}: {len(stale)} file(s) not regenerated by the last run')
        for s in stale:
            print(f"   - {s['file']} ({s['size_kb']} KB, {s['age_days']}d old)")

    OUT.write_text(json.dumps(report, indent=2, default=str),
                   encoding='utf-8')
    print('WROTE', OUT.relative_to(ROOT))
    n = sum(len(v) for v in report['stale_files'].values())
    print(f'Stale-artifact audit: {n} file(s) listed (informational only; '
          'nothing deleted).')


if __name__ == '__main__':
    main()
